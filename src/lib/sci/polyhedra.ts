/** Every polygon of a tiling whose centre lies in a box, as point lists. */
export function patch(t: TilingDef, x0: number, x1: number, y0: number, y1: number): { n: number; p: P2[] }[] {
  const det = t.a1[0] * t.a2[1] - t.a1[1] * t.a2[0], out: { n: number; p: P2[] }[] = [];
  const toUV = (x: number, y: number) => [(x * t.a2[1] - y * t.a2[0]) / det, (t.a1[0] * y - t.a1[1] * x) / det];
  const cs = [toUV(x0, y0), toUV(x1, y0), toUV(x0, y1), toUV(x1, y1)];
  const pad = 2, u0 = Math.floor(Math.min(...cs.map((c) => c[0]))) - pad, u1 = Math.ceil(Math.max(...cs.map((c) => c[0]))) + pad, w0 = Math.floor(Math.min(...cs.map((c) => c[1]))) - pad, w1 = Math.ceil(Math.max(...cs.map((c) => c[1]))) + pad;
  for (let i = u0; i <= u1; i++) for (let j = w0; j <= w1; j++) for (const m of t.motif) {
    const c: P2 = [m.c[0] + i * t.a1[0] + j * t.a2[0], m.c[1] + i * t.a1[1] + j * t.a2[1]];
    if (c[0] < x0 - 3 || c[0] > x1 + 3 || c[1] < y0 - 3 || c[1] > y1 + 3) continue;
    out.push({ n: m.n, p: polygon({ ...m, c }) });
  }
  return out;
}
export const polygonArea = (n: number) => (n / 4) / Math.tan(Math.PI / n);
export const interiorAngle = (n: number) => 180 - 360 / n;
