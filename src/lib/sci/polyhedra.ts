export type P2 = [number, number];
export type Motif = { n: number; c: P2; rot: number }; // regular n-gon, edge 1, centre c, first vertex at angle rot (degrees)
export type TilingDef = { id: string; name: string; config: string; kind: 'regular' | 'semi-regular'; a1: P2; a2: P2; motif: Motif[] };
const r3 = Math.sqrt(3);
const rot60 = (a: P2): P2 => [a[0] / 2 - (a[1] * r3) / 2, (a[0] * r3) / 2 + a[1] / 2];
export function polygon(m: Motif): P2[] {
  const R = 1 / (2 * Math.sin(Math.PI / m.n)), out: P2[] = [];
  for (let k = 0; k < m.n; k++) { const t = ((m.rot + (360 * k) / m.n) * Math.PI) / 180; out.push([m.c[0] + R * Math.cos(t), m.c[1] + R * Math.sin(t)]); }
  return out;
}
/** Add the unit triangles that fill the gaps between the given polygons (used for the snub tilings). */
function fillTriangles(a1: P2, a2: P2, motif: Motif[]): Motif[] {
  const polys: P2[][] = [], verts: P2[] = [];
  for (let i = -2; i <= 2; i++) for (let j = -2; j <= 2; j++) for (const m of motif) {
    const p = polygon({ ...m, c: [m.c[0] + i * a1[0] + j * a2[0], m.c[1] + i * a1[1] + j * a2[1]] }); polys.push(p); verts.push(...p);
  }
  const key = (p: P2) => `${Math.round(p[0] * 1e6)},${Math.round(p[1] * 1e6)}`, vset = new Map<string, P2>();
  for (const v of verts) vset.set(key(v), v);
  const V = [...vset.values()], found = new Map<string, Motif>();
  const det = a1[0] * a2[1] - a1[1] * a2[0];
  const inside = (q: P2, poly: P2[]) => { let w = false; for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) { const [xi, yi] = poly[i], [xj, yj] = poly[j]; if ((yi > q[1]) !== (yj > q[1]) && q[0] < ((xj - xi) * (q[1] - yi)) / (yj - yi) + xi) w = !w; } return w; };
  for (let i = 0; i < V.length; i++) for (let j = i + 1; j < V.length; j++) {
    const [x1, y1] = V[i], [x2, y2] = V[j];
    if (Math.abs(Math.hypot(x2 - x1, y2 - y1) - 1) > 1e-6) continue;
    for (const sgn of [1, -1]) {
      const apex: P2 = [(x1 + x2) / 2 - (sgn * (y2 - y1) * r3) / 2, (y1 + y2) / 2 + (sgn * (x2 - x1) * r3) / 2];
      if (!vset.has(key(apex))) continue;
      const c: P2 = [(x1 + x2 + apex[0]) / 3, (y1 + y2 + apex[1]) / 3];
      if (polys.some((p) => inside(c, p))) continue;
      // Keep it once, in the fundamental cell.
      const u = (c[0] * a2[1] - c[1] * a2[0]) / det, w = (a1[0] * c[1] - a1[1] * c[0]) / det;
      if (u < -1e-9 || u >= 1 - 1e-9 || w < -1e-9 || w >= 1 - 1e-9) continue;
      const rot = (Math.atan2(V[i][1] - c[1], V[i][0] - c[0]) * 180) / Math.PI;
      found.set(key(c), { n: 3, c, rot });
    }
  }
  return [...motif, ...found.values()];
}
