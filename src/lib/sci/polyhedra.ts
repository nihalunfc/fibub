// Platonic and Archimedean solids built from their vertex coordinates (closed-form formulas), with
// edges found as the shortest vertex distances and faces traced around the surface; duals by polar
// reciprocation in the midsphere; and the 11 regular and semi-regular plane tilings from a lattice
// and a motif of regular polygons. Plain TypeScript, no DOM.

export type V3 = [number, number, number];
const PHI = (1 + Math.sqrt(5)) / 2;
const sub = (a: V3, b: V3): V3 => [a[0] - b[0], a[1] - b[1], a[2] - b[2]];
const dot = (a: V3, b: V3) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
const cross = (a: V3, b: V3): V3 => [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]];
const norm = (a: V3) => Math.hypot(a[0], a[1], a[2]);
const scl = (a: V3, k: number): V3 => [a[0] * k, a[1] * k, a[2] * k];

