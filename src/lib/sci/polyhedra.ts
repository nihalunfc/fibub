/** Every choice of signs for the non-zero entries. */
function signs(p: number[]): number[][] {
  let out: number[][] = [[]];
  for (const x of p) out = out.flatMap((s) => (x === 0 ? [[...s, 0]] : [[...s, x], [...s, -x]]));
  return out;
}
const EVEN: number[][] = [[0, 1, 2], [1, 2, 0], [2, 0, 1]], ODD: number[][] = [[0, 2, 1], [2, 1, 0], [1, 0, 2]];
const permute = (p: number[], perms: number[][]) => perms.map((q) => q.map((i) => p[i]));
const allPerms = (p: number[]) => [...permute(p, EVEN), ...permute(p, ODD)];
/** All sign changes of all (even, or all) permutations, without repeats. */
function pts(list: number[][], perms: 'even' | 'all', filter?: (v: number[], parity: number) => boolean): V3[] {
  const out = new Map<string, V3>();
  for (const p of list) {
    const ps = perms === 'even' ? permute(p, EVEN).map((v) => [v, 0] as const) : [...permute(p, EVEN).map((v) => [v, 0] as const), ...permute(p, ODD).map((v) => [v, 1] as const)];
    for (const [v, par] of ps) for (const s of signs(v)) {
      if (filter && !filter(s, par)) continue;
      out.set(s.map((x) => x.toFixed(9)).join(), s as V3);
    }
  }
  return [...out.values()];
}
const plusCount = (v: number[]) => v.filter((x) => x > 0).length;
const minusCount = (v: number[]) => v.filter((x) => x < 0).length;

const TRIB = (() => { let t = 1.8; for (let k = 0; k < 60; k++) t -= (t ** 3 - t * t - t - 1) / (3 * t * t - 2 * t - 1); return t; })();
/** Rotate p about the unit axis a by angle t (Rodrigues). */
function rotate(p: V3, a: V3, t: number): V3 {
  const c = Math.cos(t), s = Math.sin(t), k = dot(a, p) * (1 - c), x = cross(a, p);
  return [p[0] * c + x[0] * s + a[0] * k, p[1] * c + x[1] * s + a[1] * k, p[2] * c + x[2] * s + a[2] * k];
}
const unit = (a: V3) => scl(a, 1 / norm(a));
/**
 * A snub polyhedron as the orbit of one point under the rotation group generated by turns about
 * neighbouring m-fold (A) and 3-fold (B) axes, with C the 2-fold axis between them. The point p is
 * chosen so that the chords to its images about A, B and C are equal: sin(π/m)·√(1 − (A·p)²) =
 * sin(π/3)·√(1 − (B·p)²) = √(1 − (C·p)²), solved by Newton's method on the sphere.
 */
function snub(A: V3, B: V3, C: V3, m: number): V3[] {
  const ch = (p: V3) => [Math.sin(Math.PI / m) * Math.sqrt(1 - dot(A, p) ** 2), Math.sin(Math.PI / 3) * Math.sqrt(1 - dot(B, p) ** 2), Math.sqrt(1 - dot(C, p) ** 2)];
  const F = (p: V3) => { const c = ch(p); return [c[0] - c[1], c[1] - c[2]]; };
  let p = unit([A[0] + B[0] + C[0], A[1] + B[1] + C[1], A[2] + B[2] + C[2]]);
  const e1 = unit(cross(p, A)), e2 = unit(cross(p, e1));
  let u = 0, w = 0;
  const at = (u: number, w: number) => unit([p[0] + u * e1[0] + w * e2[0], p[1] + u * e1[1] + w * e2[1], p[2] + u * e1[2] + w * e2[2]]);
  for (let k = 0; k < 60; k++) {
    const f0 = F(at(u, w)), h = 1e-7, fu = F(at(u + h, w)), fw = F(at(u, w + h));
    const J = [[(fu[0] - f0[0]) / h, (fw[0] - f0[0]) / h], [(fu[1] - f0[1]) / h, (fw[1] - f0[1]) / h]], det = J[0][0] * J[1][1] - J[0][1] * J[1][0];
    const du = (f0[0] * J[1][1] - f0[1] * J[0][1]) / det, dw = (J[0][0] * f0[1] - J[1][0] * f0[0]) / det;
    u -= du; w -= dw;
    if (Math.abs(du) + Math.abs(dw) < 1e-15) break;
  }
  p = at(u, w);
  const out = new Map<string, V3>(), queue: V3[] = [p], key = (q: V3) => q.map((x) => x.toFixed(8)).join();
  out.set(key(p), p);
  while (queue.length) {
    const q = queue.pop()!;
    for (const r of [rotate(q, A, (2 * Math.PI) / m), rotate(q, B, (2 * Math.PI) / 3)]) { const k = key(r); if (!out.has(k)) { out.set(k, r); queue.push(r); } }
  }
  return [...out.values()];
}
