// ---------- Building a polyhedron ----------
export type Poly = { v: V3[]; f: number[][]; edges: [number, number][] };
/** Edges: the pairs at the shortest distance. Faces: walk each directed edge, turning to the next neighbour round each vertex. */
export function fromVertices(raw: V3[]): Poly {
  const n = raw.length;
  let dmin = Infinity;
  for (let i = 0; i < n; i++) for (let j = i + 1; j < n; j++) dmin = Math.min(dmin, norm(sub(raw[i], raw[j])));
  const v = raw.map((p) => scl(p, 1 / dmin)); // edge length 1
  const nb: number[][] = v.map(() => []), edges: [number, number][] = [];
  for (let i = 0; i < n; i++) for (let j = i + 1; j < n; j++) if (Math.abs(norm(sub(v[i], v[j])) - 1) < 1e-6) { nb[i].push(j); nb[j].push(i); edges.push([i, j]); }
  // Order each vertex's neighbours anticlockwise seen from outside.
  for (let i = 0; i < n; i++) {
    const up = scl(v[i], 1 / norm(v[i])), ref = sub(v[nb[i][0]], v[i]);
    const e1 = sub(ref, scl(up, dot(ref, up))), e2 = cross(up, e1);
    nb[i].sort((a, b) => { const da = sub(v[a], v[i]), db = sub(v[b], v[i]); return Math.atan2(dot(da, e2), dot(da, e1)) - Math.atan2(dot(db, e2), dot(db, e1)); });
  }
  const used = new Set<string>(), f: number[][] = [];
  for (const [a0, b0] of edges) for (const [a, b] of [[a0, b0], [b0, a0]]) {
    if (used.has(`${a},${b}`)) continue;
    const face = [a]; let u = a, w = b;
    for (let guard = 0; guard < 20; guard++) {
      used.add(`${u},${w}`);
      if (w === a) break;
      face.push(w);
      const ring = nb[w], k = ring.indexOf(u), next = ring[(k - 1 + ring.length) % ring.length];
      u = w; w = next;
    }
    f.push(face);
  }
  // Make every face anticlockwise seen from outside.
  for (const face of f) { const nrm = faceNormal(v, face), c = centroid(v, face); if (dot(nrm, c) < 0) face.reverse(); }
  return { v, f, edges };
}
export const centroid = (v: V3[], face: number[]): V3 => scl(face.reduce<V3>((s, i) => [s[0] + v[i][0], s[1] + v[i][1], s[2] + v[i][2]], [0, 0, 0]), 1 / face.length);
function faceNormal(v: V3[], face: number[]): V3 {
  let nx = 0, ny = 0, nz = 0;
  for (let i = 0; i < face.length; i++) { const a = v[face[i]], b = v[face[(i + 1) % face.length]]; nx += (a[1] - b[1]) * (a[2] + b[2]); ny += (a[2] - b[2]) * (a[0] + b[0]); nz += (a[0] - b[0]) * (a[1] + b[1]); }
  const c = [nx, ny, nz] as V3; return scl(c, 1 / norm(c));
}
export const normal = faceNormal;
/** Polygon area (the face is flat). */
export function faceArea(v: V3[], face: number[]): number {
  let s: V3 = [0, 0, 0];
  for (let i = 0; i < face.length; i++) s = [s[0] + cross(v[face[i]], v[face[(i + 1) % face.length]])[0], s[1] + cross(v[face[i]], v[face[(i + 1) % face.length]])[1], s[2] + cross(v[face[i]], v[face[(i + 1) % face.length]])[2]];
  return Math.abs(dot(s, faceNormal(v, face))) / 2;
}
/** Volume by summing pyramids from the centre to each face, and surface area. */
export function measure(p: Poly) {
  let area = 0, vol = 0;
  for (const face of p.f) { const A = faceArea(p.v, face); area += A; vol += (A * Math.abs(dot(faceNormal(p.v, face), p.v[face[0]]))) / 3; }
  const circ = Math.max(...p.v.map(norm));
  const mid = norm(scl([p.v[p.edges[0][0]], p.v[p.edges[0][1]]].reduce<V3>((s, x) => [s[0] + x[0], s[1] + x[1], s[2] + x[2]], [0, 0, 0]), 0.5));
  return { area, volume: vol, circumradius: circ, midradius: mid };
}
/** Faces by number of sides, e.g. {3: 8, 4: 6}. */
export function faceCounts(p: Poly): Record<number, number> { const c: Record<number, number> = {}; for (const f of p.f) c[f.length] = (c[f.length] ?? 0) + 1; return c; }
/** Vertex configuration: the sides of the faces round a vertex, in order, written the smallest way, e.g. "3.4.3.4". */
export function vertexConfig(p: Poly, i: number): string {
  const faces = p.f.filter((f) => f.includes(i));
  // Order the faces round the vertex: each next face shares the edge (i, w).
  const ordered: number[][] = [faces[0]];
  while (ordered.length < faces.length) {
    const last = ordered[ordered.length - 1], k = last.indexOf(i), prev = last[(k - 1 + last.length) % last.length];
    const nxt = faces.find((f) => !ordered.includes(f) && f.includes(prev));
    if (!nxt) break; ordered.push(nxt);
  }
  return canonicalCycle(ordered.map((f) => f.length));
}
/** The smallest rotation or reflection of a cyclic list, joined with dots. */
export function canonicalCycle(a: number[]): string {
  const cands: string[] = [];
  for (const s of [a, [...a].reverse()]) for (let k = 0; k < s.length; k++) cands.push([...s.slice(k), ...s.slice(0, k)].map((x) => String(x).padStart(2, '0')).join('.'));
  return cands.sort()[0].split('.').map(Number).join('.');
}
/** The dual by polar reciprocation in the midsphere: one vertex per face, one face per vertex. */
export function dual(p: Poly): Poly {
  const rho = measure(p).midradius, r2 = rho * rho;
  const v = p.f.map((face) => { const n = faceNormal(p.v, face), d = dot(n, p.v[face[0]]); return scl(n, r2 / d); });
  const f = p.v.map((_, i) => {
    const faces = p.f.map((face, k) => [face, k] as const).filter(([face]) => face.includes(i));
    const ordered = [faces[0]];
    while (ordered.length < faces.length) {
      const [last] = ordered[ordered.length - 1], k = last.indexOf(i), nextV = last[(k + 1) % last.length];
      const nxt = faces.find(([face]) => !ordered.some(([o]) => o === face) && face.includes(nextV) && face[(face.indexOf(nextV) + 1) % face.length] === i);
      if (!nxt) break; ordered.push(nxt);
    }
    return ordered.map(([, k]) => k);
  });
  for (const face of f) { const n = faceNormal(v, face); if (dot(n, centroid(v, face)) < 0) face.reverse(); }
  const edges: [number, number][] = []; const seen = new Set<string>();
  for (const face of f) for (let k = 0; k < face.length; k++) { const a = face[k], b = face[(k + 1) % face.length], key = a < b ? `${a},${b}` : `${b},${a}`; if (!seen.has(key)) { seen.add(key); edges.push(a < b ? [a, b] : [b, a]); } }
  return { v, f, edges };
}
