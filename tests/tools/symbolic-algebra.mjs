// #542 symbolic algebra (lite CAS)
export const path = '/science/symbolic-algebra/';
export default async ({ page, check, BASE }) => {
  const R = '.sac ';
  const big = () => page.textContent(R + '.sa-big');
  const op = async (o) => { await page.click(`${R}.sa-ops button[data-op=${o}]`); await page.waitForTimeout(150); };
  const type = async (s) => { await page.fill(R + '.sa-in', s); await page.waitForTimeout(450); };
  await page.goto(`${BASE}/science/symbolic-algebra/`); await page.waitForTimeout(600);
  check((await big()) === '−x²·e^(−x) − 2x·e^(−x) − 2e^(−x)' && (await page.textContent(R + '.sa-facts')).includes('integration by parts'), `cas: example integral by parts (${await big()})`);
  check((await page.inputValue(R + '.sa-py')) === '-x**2*exp(-x) - 2*x*exp(-x) - 2*exp(-x)' && (await page.inputValue(R + '.sa-tex')).startsWith('-x^{2} e^{-x}'), 'cas: SymPy and LaTeX copies');
  check(await page.isVisible(R + '.sa-fig') && (await page.textContent(R + '.sa-leg')).includes('antiderivative'), 'cas: graph of the expression and its antiderivative');
  await page.click(R + '.sa-ex[data-ex^="(x^3+1)"]'); await page.waitForTimeout(200);
  check((await big()) === 'x²/2 + 3x − 2ln|x − 1| + 9ln|x − 2|' && (await page.textContent(R + '.sa-facts')).includes('partial fractions'), `cas: partial fractions example (${await big()})`);
  await page.fill(R + '.sa-a', '0'); await page.fill(R + '.sa-b', 'pi'); await type('sin(x)');
  check((await big()) === '2' && (await page.textContent(R + '.sa-facts')).includes('numerical integral'), 'cas: definite integral of sin from 0 to π');
  await type('1/x'); await page.fill(R + '.sa-a', '-1'); await page.fill(R + '.sa-b', '1'); await page.waitForTimeout(450);
  check((await big()) === 'Not worked out' && (await page.textContent(R + '.sa-note')).includes('improper'), 'cas: improper integral refused');
  await page.fill(R + '.sa-a', ''); await page.fill(R + '.sa-b', ''); await type('e^(x^2)');
  check((await big()) === 'Could not integrate' && (await page.textContent(R + '.sa-note')).includes('no answer in elementary functions'), 'cas: honest could-not-integrate');
  await page.fill(R + '.sa-a', '0'); await page.waitForTimeout(450);
  check((await page.textContent(R + '.sa-err')).includes('both From and To'), 'cas: one limit only is refused');
  await page.fill(R + '.sa-a', '');
  await page.click(R + '.sa-ex[data-ex^="x^6"]'); await page.waitForTimeout(200);
  check((await big()) === '(x − 1)(x + 1)(x² − x + 1)(x² + x + 1)' && (await page.textContent(R + '.sa-facts')).includes('1, −1'), `cas: factor x⁶ − 1 with roots (${await big()})`);
  await type('x^2 + 1');
  check((await page.textContent(R + '.sa-note')).includes('irreducible'), 'cas: irreducible polynomial noted');
  await type('2x^2y + 4xy');
  check((await big()) === '2xy(x + 2)' && (await page.textContent(R + '.sa-note')).includes('Several letters'), 'cas: several letters, common factor');
  await page.click(R + '.sa-ex[data-ex^="x^2 sin"]'); await page.waitForTimeout(200);
  check((await big()) === 'x²·cos(x) + 2x·sin(x)' && (await page.textContent(R + '.sa-leg')).includes('derivative'), 'cas: product rule example');
  await page.selectOption(R + '.sa-n', '2'); await page.waitForTimeout(200);
  check((await big()) === '−x²·sin(x) + 4x·cos(x) + 2sin(x)', `cas: second derivative (${await big()})`);
  await page.selectOption(R + '.sa-n', '1');
  await type('a t^2 + b t'); await page.selectOption(R + '.sa-var', 't'); await page.waitForTimeout(200);
  check((await big()) === '2at + b' && (await page.$$eval(R + '.sa-var option', (o) => o.map((x) => x.textContent).join(','))) === 'a,b,t' && await page.isHidden(R + '.sa-fig'), 'cas: derivative with respect to another letter, no graph for several letters');
  await page.click(R + '.sa-ex[data-ex^="(x^3-8)"]'); await page.waitForTimeout(200);
  check((await big()) === '(x² + 2x + 4)/(x + 2)', 'cas: simplify cancels');
  await type('sin(x)^2 + cos(x)^2 + (x+1)^2 - x^2');
  check((await big()) === '2x + 2', `cas: simplify identity and squares (${await big()})`);
  await op('expand'); await type('(x+y)^3');
  check((await big()) === 'x³ + 3x²y + 3xy² + y³', `cas: expand (x + y)³ (${await big()})`);
  await op('subs'); await type('x^2 + 2x + 1'); await page.fill(R + '.sa-sub', 'x = t - 1'); await page.waitForTimeout(450);
  check((await big()) === 't²', 'cas: substitute an expression');
  await page.fill(R + '.sa-sub', 'x = 1/2'); await page.waitForTimeout(450);
  check((await big()) === '9/4' && (await page.textContent(R + '.sa-facts')).includes('2.25'), 'cas: substitute a value, exact and decimal');
  await page.fill(R + '.sa-sub', 'x 2'); await page.waitForTimeout(450);
  check((await page.textContent(R + '.sa-err')).includes('should look like x = 2'), 'cas: bad substitution message');
  await type('(x+1');
  check((await page.textContent(R + '.sa-err')) === 'A bracket is not closed.' && await page.isHidden(R + '.sa-out'), 'cas: parse error message');
  await type('sin x');
  check((await page.textContent(R + '.sa-err')).includes('sin needs brackets'), 'cas: function needs brackets');
  await op('simplify'); await type('2xy + 3yx');
  check((await page.textContent(R + '.sa-read')) === 'Read as: 5xy' && (await big()) === '5xy', 'cas: read-as line and implicit multiplication');
  await type('sqrt(12) + sin(pi/6)');
  check((await big()) === '2√3 + 1/2', 'cas: exact values');
  { await page.context().grantPermissions(['clipboard-read', 'clipboard-write']); await page.click(R + '.sa-copy[data-t=".sa-py"]'); await page.waitForTimeout(100); check(['Copied', 'Press Ctrl+C'].includes(await page.textContent(R + '.sa-copy[data-t=".sa-py"]')), 'cas: copy button'); }
  await op('int'); await type('x ln(x)');
  { const [d] = await Promise.all([page.waitForEvent('download'), page.click(R + '.dl button[data-f=png]')]); check(d.suggestedFilename() === 'symbolic-int.png', 'cas: image download'); }
};
