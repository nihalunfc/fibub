// Supply and demand: the made-up example, every policy, constant elasticity, arc elasticity, downloads and bad input.
export const path = '/science/supply-demand/';
export default async ({ page, check, BASE, OUT, readFileSync }) => {
  const dl = async (sel) => { await page.locator(sel).scrollIntoViewIfNeeded(); const [d] = await Promise.all([page.waitForEvent('download'), page.click(sel)]); const f = OUT + d.suggestedFilename(); await d.saveAs(f); return f; };
  const big = () => page.textContent('.sd-big');
  const wait = (re) => page.waitForFunction((s) => new RegExp(s).test(document.querySelector('.sd-big')?.textContent || ''), re.source);
  await page.goto(BASE + path);
  check(/^Market price \$20, quantity 60; with the tax quantity 52$/.test(await big()), `supply-demand: example with $6 tax (${await big()})`);
  const facts = await page.textContent('.sd-facts');
  check(/−0\.667/.test(facts) && /1\.33/.test(facts) && /\$900/.test(facts) && /\$450/.test(facts) && /\$24/.test(facts) && /66\.7 %/.test(facts), `supply-demand: elasticities, surplus, DWL, incidence (${facts.slice(0, 300)})`);
  const tab = await page.textContent('.sd-tab');
  check(/\$24/.test(tab) && /\$18/.test(tab) && /\$676/.test(tab) && /\$338/.test(tab) && /\$312/.test(tab) && /\$1,326/.test(tab), `supply-demand: before/after table (${tab})`);
  const csv = readFileSync(await dl('.sd-csv'), 'utf8');
  check(/Consumer surplus,\$900,\$676,−\$224/.test(csv) && /Deadweight loss,24/.test(csv), 'supply-demand: CSV download');
  const pdf = readFileSync(await dl('.dl [data-f=pdf]'));
  check(pdf.slice(0, 4).toString() === '%PDF', 'supply-demand: PDF report');
  await page.selectOption('.sd-pol', 'subsidy'); await page.fill('.sd-amt', '3');
  await wait(/quantity 64$/);
  check(/Deadweight loss\$6s/.test(await page.textContent('.sd-facts')) && /Government cost/.test(await page.textContent('.sd-tab')), 'supply-demand: subsidy 3 → Q 64, DWL 6');
  await page.selectOption('.sd-pol', 'ceiling'); await page.fill('.sd-amt', '16');
  await wait(/price \$16 quantity 44$/);
  check(/Shortage24/.test(await page.textContent('.sd-facts')) && /\$96/.test(await page.textContent('.sd-facts')), 'supply-demand: ceiling 16 → shortage 24, DWL 96');
  await page.fill('.sd-amt', '25');
  await wait(/^Market price \$20, quantity 60$/);
  check(/does not bind/.test(await page.textContent('.sd-facts')), 'supply-demand: ceiling above the market price does not bind');
  await page.selectOption('.sd-pol', 'floor');
  await wait(/price \$25 quantity 50$/);
  check(/Unsold surplus30/.test(await page.textContent('.sd-facts')) && /\$37\.5/.test(await page.textContent('.sd-facts')), 'supply-demand: floor 25 → surplus 30, DWL 37.5');
  await page.selectOption('.sd-pol', 'none');
  await wait(/^Market price \$20, quantity 60$/);
  check(true, 'supply-demand: no policy');
  await page.click('.sd-model button[data-m=ce]');
  await page.selectOption('.sd-pol', 'tax'); await page.fill('.sd-amt', '2');
  await wait(/quantity 29\.22$/);
  check(/Market price \$10, quantity 31\.62/.test(await big()) && /\$2\.408/.test(await page.textContent('.sd-facts')), `supply-demand: constant elasticity with tax 2 (${await big()})`);
  await page.fill('.sd-de', '-0.5');
  await page.waitForFunction(() => /unbounded/.test(document.querySelector('.sd-facts')?.textContent || ''));
  check(/Market price \$100, quantity 100/.test(await big()) && /unlimited/.test(await page.textContent('.sd-tab')), `supply-demand: inelastic CE demand has unbounded consumer surplus (${await big()})`);
  await page.fill('.sd-de', '0.5');
  await page.waitForSelector('.sd-err:not([hidden])');
  check(/must be negative/.test(await page.textContent('.sd-err')), 'supply-demand: positive demand elasticity is explained');
  await page.click('.sd-model button[data-m=linear]');
  await page.fill('.sd-sa', '200');
  await page.waitForSelector('.sd-err:not([hidden])');
  check(/do not cross/.test(await page.textContent('.sd-err')), 'supply-demand: curves that never cross are explained');
  await page.fill('.sd-sa', '-20');
  check(/Arc elasticity −1\.222/.test(await page.textContent('.sd-arc')) && /−1\b/.test(await page.textContent('.sd-arch')), `supply-demand: arc elasticity (${await page.textContent('.sd-arc')})`);
  await page.fill('.sd-p2', '10');
  await page.waitForFunction(() => /same/.test(document.querySelector('.sd-arch')?.textContent || ''));
  check(true, 'supply-demand: equal prices explained');
  await page.setViewportSize({ width: 375, height: 800 }); await page.fill('.sd-p2', '12'); await page.selectOption('.sd-pol', 'tax'); await page.fill('.sd-amt', '6');
  await wait(/quantity 52$/);
  await page.screenshot({ path: OUT + 'supply-demand-375.png', fullPage: true });
  await page.setViewportSize({ width: 1280, height: 800 });
};
