// #724 Factor analysis: the made-up example, every option, correlation-matrix input, CSV, report, bad input.
export const path = '/science/factor-analysis/';
export default async ({ page, check, BASE, OUT, readFileSync }) => {
  await page.goto(BASE + path);
  await page.waitForSelector('.fa-out:not([hidden])');
  const TXT = (sel) => [...document.querySelectorAll(sel + ' tr')].map((r) => [...r.cells].map((c) => c.textContent).join(' ')).join(' | ');
  const facts = await page.textContent('.fa-facts');
  check(/0\.801 \(meritorious\)/.test(facts) && /χ²\(28\) = 290\.3, p < 0\.001/.test(facts) && /2 factors/.test(facts), `factor: KMO, Bartlett, parallel analysis (${facts})`);
  const eig = await page.evaluate(TXT, '.fa-eig');
  check(/1 3\.123 39\.0 39\.0/.test(eig) && /2 1\.479/.test(eig), `factor: eigenvalues (${eig.slice(0, 120)})`);
  let L = await page.evaluate(TXT, '.fa-load');
  check(/V2 0\.808 −0\.120/.test(L) && /V8 −0\.154 0\.652/.test(L), `factor: promax pattern (${L.slice(0, 200)})`);
  check(/F1 1\.000 0\.467/.test(await page.evaluate(TXT, '.fa-phi')), 'factor: factor correlation 0.467');
  check((await page.locator('.fa-load td.fa-dim').count()) === 8 && (await page.locator('.fa-load td.fa-hi').count()) === 8, 'factor: small loadings greyed, main ones bold');
  check(await page.evaluate(() => { const c = document.querySelector('.fa-fig'); return c.width > 100 && c.getAttribute('aria-label').includes('2 eigenvalues'); }), 'factor: scree plot drawn');
  await page.selectOption('.fa-cut', '0');
  await page.waitForFunction(() => document.querySelectorAll('.fa-load td.fa-dim').length === 0);
  check(true, 'factor: show all loadings');
  await page.selectOption('.fa-method', 'ml');
  await page.selectOption('.fa-rot', 'varimax');
  await page.waitForFunction(() => /χ²\(13\) = 10\.77, p = 0\.630/.test(document.querySelector('.fa-fit').textContent));
  L = await page.evaluate(TXT, '.fa-load');
  check(/V1 0\.630 0\.218/.test(L) && (await page.isHidden('.fa-phiw')), `factor: ML varimax (${L.slice(0, 120)})`);
  await page.selectOption('.fa-rot', 'none');
  await page.selectOption('.fa-k', '3');
  await page.waitForFunction(() => /3 factors/.test(document.querySelector('.fa-lh').textContent) && /unrotated/.test(document.querySelector('.fa-lh').textContent));
  check((await page.locator('.fa-load thead th').count()) === 7, 'factor: three factors chosen by hand');
  await page.selectOption('.fa-k', '1');
  await page.selectOption('.fa-method', 'pa');
  await page.waitForFunction(() => /1 factor$/.test(document.querySelector('.fa-lh').textContent));
  check(true, 'factor: one factor, principal axis');
  await page.selectOption('.fa-k', 'auto');
  await page.selectOption('.fa-rot', 'promax');
  await page.waitForFunction(() => /V2 0\.808/.test([...document.querySelectorAll('.fa-load td')].map((c) => c.textContent).join(' ')));
  const [d] = await Promise.all([page.waitForEvent('download'), page.click('.fa-csv')]);
  const f = OUT + 'fa.csv'; await d.saveAs(f);
  const c = readFileSync(f, 'utf8').trim().split('\n');
  check(c[0] === 'Variable,F1,F2,h²,u²,MSA' && /^V2,0\.80799/.test(c[2]) && c.length === 9, `factor: CSV (${c[2]})`);
  const [w] = await Promise.all([page.waitForEvent('download'), page.click('.fa .dl button[data-f=pdf]')]);
  check(/\.pdf$/.test(w.suggestedFilename()), 'factor: PDF report');
  // Correlation matrix input (lower triangle) with n.
  await page.selectOption('.fa-form', 'corr');
  await page.fill('.fa-in', '\tA\tB\tC\tD\nA\t1\nB\t0.6\t1\nC\t0.5\t0.55\t1\nD\t0.1\t0.15\t0.2\t1');
  await page.fill('.fa-n', '');
  await page.waitForFunction(() => /number of people/.test(document.querySelector('.fa-err').textContent) && !document.querySelector('.fa-err').hidden);
  check(true, 'factor: matrix needs n');
  await page.fill('.fa-n', '120');
  await page.selectOption('.fa-k', '1');
  await page.waitForSelector('.fa-out:not([hidden])');
  L = await page.evaluate(TXT, '.fa-load');
  check(/^Variable F1/.test(L) && /\| A 0\.7/.test(L) && /People, variables120, 4/.test(await page.textContent('.fa-facts')), `factor: correlation matrix input (${L.slice(0, 80)})`);
  await page.fill('.fa-in', 'A\tB\tC\n1\t0.5\t0.2\n0.4\t1\t0.3\n0.2\t0.3\t1');
  await page.waitForFunction(() => /not symmetric/.test(document.querySelector('.fa-err').textContent));
  check(true, 'factor: unsymmetric matrix refused');
  await page.selectOption('.fa-form', 'raw');
  await page.fill('.fa-in', 'a\tb\tc\n1\t2\t3\n2\t3\t1\n3\t1\t2');
  await page.waitForFunction(() => /more people than variables/.test(document.querySelector('.fa-err').textContent));
  check(true, 'factor: too few rows');
  await page.fill('.fa-in', 'a\tb\tc\n1\t2\tx');
  await page.waitForFunction(() => /"x" in row 1 \(c\) is not a number/.test(document.querySelector('.fa-err').textContent));
  check(true, 'factor: text reported');
};
