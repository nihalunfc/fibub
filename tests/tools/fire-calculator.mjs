// #1733 FIRE calculator
export const path = '/money/fire-calculator/';
export default async ({ page, check, BASE }) => {
  await page.goto(`${BASE}/money/fire-calculator/`); await page.waitForTimeout(300);
  const set = async (k, v) => { await page.fill(`.fi [data-k="${k}"]`, v); await page.waitForTimeout(80); };
  await page.selectOption('.fi [data-k="cur"]', 'USD');
  await set('spend', '40000'); await set('wr', '4'); await set('income', '60000'); await set('saved', '0'); await set('ret', '0');
  check((await page.textContent('.fi .fi-num')).includes('1,000,000'), 'fire-calculator: spend 40,000 at 4% gives 1,000,000');
  check((await page.textContent('.fi .fi-years')).includes('50'), 'fire-calculator: 20,000 a year at 0% return takes 50 years');
  await set('wr', '3');
  check((await page.textContent('.fi .fi-num')).includes('1,333,333'), 'fire-calculator: a 3% rate raises the number');
  await set('saved', '2000000');
  check((await page.textContent('.fi .fi-years')).includes('Already'), 'fire-calculator: enough saved says already there');
  check((await page.$$('.fi .fi-body tr')).length === 7, 'fire-calculator: seven rows in the saving-rate table');
  await set('wr', '0');
  check(await page.isVisible('.fi .fi-err'), 'fire-calculator: bad rate shows a message');
  // new options (details are closed by default, so open them before filling)
  await page.evaluate(() => document.querySelectorAll('.tool-ui details').forEach((d) => (d.open = true)));
  await set('wr', '4'); await set('saved', '0'); await set('income', '60000'); await set('spend', '40000');
  check(/50 years/.test(await page.textContent('.fi .fi-head')) && /÷ 4%/.test(await page.textContent('.fi .fi-work')), 'fire-calculator: one-line answer and the working ' + await page.textContent('.fi .fi-head'));
  check(await page.inputValue('.fi [data-k="rs"]') === '33' && await page.inputValue('.fi [data-k="rate"]') === '33.3', 'fire-calculator: saving rate follows income and spending');
  await page.evaluate(() => { const s = document.querySelector('.fi [data-k="rs"]'); s.value = '50'; s.dispatchEvent(new Event('input', { bubbles: true })); });
  await page.waitForTimeout(100);
  check(await page.inputValue('.fi [data-k="spend"]') === '30000' && (await page.textContent('.fi .fi-num')).includes('750,000'), 'fire-calculator: the saving-rate slider sets spending');
  await set('rate', '25');
  check(await page.inputValue('.fi [data-k="spend"]') === '45000' && (await page.textContent('.fi .fi-num')).includes('1,125,000'), 'fire-calculator: typing a saving rate sets spending');
  check((await page.$$('.fi .fi-body tr')).length === 7 && (await page.$$('.fi .fi-wr-body tr')).length === 4, 'fire-calculator: tables for saving rates and withdrawal rates');
  check((await page.textContent('.fi .fi-var-body')).includes('Lean') && (await page.textContent('.fi .fi-var-body')).includes('Fat'), 'fire-calculator: lean and fat rows');
  check(/Add your age/.test(await page.textContent('.fi .fi-var-body')), 'fire-calculator: coast asks for an age');
  await set('age', '40');
  check((await page.textContent('.fi .fi-var-body')).includes('Coast (stop saving by age 65)'), 'fire-calculator: coast row with an age');
  await set('other', '10000');
  check((await page.textContent('.fi .fi-var-body')).includes('875,000'), 'fire-calculator: barista number (45,000 - 10,000) / 4%');
  await set('rspend', '30000');
  check((await page.textContent('.fi .fi-num')).includes('750,000'), 'fire-calculator: a different retirement spending changes the number');
  const [dl] = await Promise.all([page.waitForEvent('download'), page.click('.fi .fi-csv')]);
  check(dl.suggestedFilename().endsWith('.csv'), 'fire-calculator: year-by-year CSV downloads');
  await set('rspend', ''); await set('saved', '-5');
  check(await page.isVisible('.fi .fi-err') && /negative/.test(await page.textContent('.fi .fi-err')), 'fire-calculator: a negative amount gets a friendly message');
  await set('saved', '0'); await set('income', '99999999999999999999');
  check(await page.isVisible('.fi .fi-err') && !/NaN/.test(await page.textContent('.fi .fi-err')), 'fire-calculator: a huge amount gets a friendly message');
};
