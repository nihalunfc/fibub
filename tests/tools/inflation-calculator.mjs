// Inflation calculator: two index values, a yearly rate, a pasted series (rebase, convert, real values), Fisher, downloads, bad input.
export const path = '/science/inflation-calculator/';
export default async ({ page, check, BASE, OUT, readFileSync }) => {
  const dl = async (sel) => { await page.locator(sel).scrollIntoViewIfNeeded(); const [d] = await Promise.all([page.waitForEvent('download'), page.click(sel)]); const f = OUT + d.suggestedFilename(); await d.saveAs(f); return f; };
  const big = () => page.textContent('.inf-big');
  const waitBig = (re) => page.waitForFunction((s) => new RegExp(s).test(document.querySelector('.inf-big')?.textContent || ''), re.source);
  const waitErr = (re = /./) => page.waitForFunction((t) => { const e = document.querySelector('.inf-err'); return e && !e.hidden && new RegExp(t).test(e.textContent || ''); }, re.source);
  await page.goto(BASE + path);
  check((await big()) === '$100.00 in 2015 = $132.40 in 2025', `inflation: two index values (${await big()})`);
  const f = await page.textContent('.inf-facts');
  check(/32\.4 %/.test(f) && /2\.85 %/.test(f) && /−24\.5 %/.test(f) && /\$75\.53/.test(f) && /index 100 → 132\.4/.test(f), `inflation: facts (${f})`);
  check(/Real rate 2\.094 %/.test(await page.textContent('.inf-real')) && /2\.154 %/.test(await page.textContent('.inf-realh')), 'inflation: Fisher uses the result (exact 2.094 %, approx 2.154 %)');
  const csv = readFileSync(await dl('.inf-csv'), 'utf8');
  check(/Equivalent at end,132\.4/.test(csv), 'inflation: CSV download');
  check(readFileSync(await dl('.dl [data-f=docx]')).slice(0, 2).toString() === 'PK', 'inflation: Word report');
  await page.fill('.inf-d1', 'Jun 2015'); await page.fill('.inf-d2', '2025-06');
  await waitBig(/in Jun 2015 =/);
  check(/over 10 years/.test(await page.textContent('.inf-facts')), 'inflation: month dates');
  await page.fill('.inf-d1', 'someday');
  await waitErr();
  check(/Write dates as a year/.test(await page.textContent('.inf-err')), 'inflation: bad date explained');
  await page.fill('.inf-d1', '2015'); await page.fill('.inf-c1', '0');
  await waitErr(/above zero/);
  check(/above zero/.test(await page.textContent('.inf-err')), 'inflation: zero index explained');
  await page.fill('.inf-c1', '100');
  await page.click('.inf-mode button[data-m=rate]');
  await waitBig(/today/);
  check((await big()) === '$100.00 today = $118.87 in 7 years' && /28\.1 years/.test(await page.textContent('.inf-facts')), `inflation: yearly rate (${await big()})`);
  await page.fill('.inf-nom', '1');
  await page.waitForFunction(() => /below zero|Below zero/.test(document.querySelector('.inf-realh')?.textContent || ''));
  check(/−1\.463 %/.test(await page.textContent('.inf-real')), `inflation: negative real rate (${await page.textContent('.inf-real')})`);
  await page.fill('.inf-pi', '10');
  await page.waitForFunction(() => /−8\.182 %/.test(document.querySelector('.inf-real')?.textContent || ''));
  check(true, 'inflation: typed inflation is kept (1 % nominal, 10 % inflation → −8.182 %)');
  await page.fill('.inf-pi', ''); await page.fill('.inf-nom', '5');
  await page.click('.inf-mode button[data-m=series]');
  await waitBig(/in 2015 = 132\.4 in 2025/);
  check(true, 'inflation: series converts 100 in 2015 to 132.4 in 2025');
  const sf = await page.textContent('.inf-facts');
  check(/Average wage: real change2\.53 %/.test(sf) && /35\.7 %|35\.8 %/.test(sf) && /yearly/.test(sf), `inflation: wage real change (${sf})`);
  await page.selectOption('.inf-base', { label: '2020' });
  await page.waitForFunction(() => /2020 = 100/.test(document.querySelector('.inf-tab thead')?.textContent || ''));
  const tab = await page.textContent('.inf-tab');
  check(/92\.166/.test(tab) && /44,?736|44736/.test(tab) && /−3\.06 %/.test(tab), `inflation: rebased to 2020 and real wages (${tab.slice(0, 200)})`);
  check(await page.isVisible('.inf-fig2'), 'inflation: nominal vs real chart shown');
  const scsv = readFileSync(await dl('.inf-csv'), 'utf8');
  check(/^Period,Price index,Rebased \(2020 = 100\),Change \(%\)/.test(scsv) && /2022,120\.3,110\.88,7\.41,48000,43291\.8,-3\.06/.test(scsv), `inflation: series CSV (${scsv.split('\n')[8]})`);
  // Monthly data gets a year-on-year column.
  const mon = ['Month\tCPI', ...Array.from({ length: 15 }, (_, i) => `${2024 + Math.floor(i / 12)}-${String((i % 12) + 1).padStart(2, '0')}\t${(100 * 1.003 ** i).toFixed(4)}`)].join('\n');
  await page.fill('.inf-data', mon);
  await page.waitForFunction(() => /Over a year/.test(document.querySelector('.inf-tab')?.textContent || ''));
  check(/monthly/.test(await page.textContent('.inf-facts')) && /3\.66 %/.test(await page.textContent('.inf-tab')), 'inflation: monthly series year-on-year 3.66 %');
  await page.fill('.inf-data', 'Year\tCPI\n2020\t100\n2019\t98');
  await waitErr();
  check(/time order/.test(await page.textContent('.inf-err')), 'inflation: out-of-order dates explained');
  await page.fill('.inf-data', 'Year\tCPI\n2020\t100\nlater\t98');
  await waitErr(/later/);
  check(/"later" is not a date/.test(await page.textContent('.inf-err')), 'inflation: bad series date explained');
};
