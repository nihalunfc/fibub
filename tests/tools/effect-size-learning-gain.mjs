// #765 Effect size and learning gain: every mode and source, level, CSV, report, bad input.
export const path = '/science/effect-size-learning-gain/';
export default async ({ page, check, BASE, OUT, readFileSync }) => {
  await page.goto(BASE + path);
  await page.waitForSelector('.es-out:not([hidden])');
  const TXT = (sel) => [...document.querySelectorAll(sel + ' tr')].map((r) => [...r.cells].map((c) => c.textContent).join(' ')).join(' | ');
  let t = await page.evaluate(TXT, '.es-tab');
  check((await page.textContent('.es-big')) === 'g = 0.605' && /Hedges' g 0\.605 0\.043 to 1\.162 medium/.test(t) && /Cohen's d 0\.615 0\.044 to 1\.180/.test(t) && /Glass's delta \(group 2 SD\) 0\.583/.test(t), `effect: two groups (${t})`);
  check(/t\(48\) = 2\.173, p = 0\.035/.test(await page.textContent('.es-facts')), 'effect: t test');
  await page.selectOption('.es-level', '0.9');
  await page.waitForFunction(() => /0\.135 to 1\.089/.test(document.querySelector('.es-tab').textContent));
  check(true, 'effect: 90 % interval');
  await page.selectOption('.es-level', '0.95');
  await page.selectOption('.es-p[data-m=groups] .es-src', 'raw');
  await page.waitForFunction(() => document.querySelector('.es-big').textContent === 'g = 1.542');
  check(true, 'effect: raw scores, unequal groups');
  const [d] = await Promise.all([page.waitForEvent('download'), page.click('.es-csv')]);
  const f = OUT + 'es.csv'; await d.saveAs(f);
  const c = readFileSync(f, 'utf8').trim().split('\n');
  check(c[0] === 'Measure,Value,95 % interval,Size' && /^Hedges' g,1\.542,/.test(c[1]), `effect: CSV (${c[1]})`);
  await page.click('.es-mode button[data-m=paired]');
  await page.waitForFunction(() => /dz = 0\.852/.test(document.querySelector('.es-big').textContent));
  t = await page.evaluate(TXT, '.es-tab');
  check(/0\.852 0\.329 to 1\.358 large/.test(t) && /dav \(change \/ average SD\) 0\.639 0\.279 to 0\.999/.test(t), `effect: paired (${t})`);
  await page.fill('.es-psd', '9.040730059');
  await page.waitForFunction(() => /0\.720/.test(document.querySelector('.es-facts').textContent));
  check(/dz = 0\.852/.test(await page.textContent('.es-big')), 'effect: SD of differences instead of r');
  await page.selectOption('.es-p[data-m=paired] .es-src', 'raw');
  await page.waitForFunction(() => /dz = 2\.405/.test(document.querySelector('.es-big').textContent));
  check(/0\.930/.test(await page.textContent('.es-facts')), 'effect: paired raw');
  await page.click('.es-mode button[data-m=gain]');
  await page.waitForFunction(() => /⟨g⟩ = 0\.265/.test(document.querySelector('.es-big').textContent));
  check(/low gain/.test(await page.textContent('.es-facts')) && /0\.279/.test(await page.textContent('.es-facts')) && (await page.locator('.es-gt tbody tr').count()) === 10, 'effect: Hake gain');
  const [w] = await Promise.all([page.waitForEvent('download'), page.click('.es .dl button[data-f=pdf]')]);
  check(/\.pdf$/.test(w.suggestedFilename()), 'effect: PDF report');
  await page.selectOption('.es-p[data-m=gain] .es-src', 'sum');
  await page.fill('.es-hpre', '40'); await page.fill('.es-max', '100'); await page.fill('.es-hpost', '70');
  await page.waitForFunction(() => /⟨g⟩ = 0\.500/.test(document.querySelector('.es-big').textContent));
  check(/medium gain/.test(await page.textContent('.es-facts')), 'effect: class means');
  await page.fill('.es-hpost', '120');
  await page.waitForFunction(() => /between 0 and the maximum/.test(document.querySelector('.es-err').textContent));
  check(true, 'effect: post above maximum refused');
  await page.click('.es-mode button[data-m=groups]');
  await page.selectOption('.es-p[data-m=groups] .es-src', 'sum');
  await page.fill('.es-s1', '0');
  await page.waitForFunction(() => /Standard deviations must be above 0/.test(document.querySelector('.es-err').textContent));
  check(true, 'effect: zero SD refused');
  await page.fill('.es-s1', 'abc');
  await page.waitForFunction(() => /Enter the group 1 SD/.test(document.querySelector('.es-err').textContent));
  check(true, 'effect: missing value named');
};
