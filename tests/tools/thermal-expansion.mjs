// #1347 thermal-expansion
export const path = '/learn/thermal-expansion/';
export default async ({ page, check, BASE }) => {
  const R = '.txp ';
  const t = (s) => page.textContent(R + s);
  const slide = async (sel, v) => { await page.$eval(R + sel, (e, v) => { e.value = v; e.dispatchEvent(new Event('input', { bubbles: true })); }, String(v)); await page.waitForTimeout(150); };
  await page.goto(BASE + path); await page.waitForTimeout(600);
  check((await t('.tx-eq')).includes('ΔL = α L ΔT = 12×10⁻⁶ /°C × 13 m × (45 − 20) °C = 3.90 mm.  Gap now = 5 mm − 3.90 mm = 1.10 mm.'), 'expansion: steel 13 m, +25 °C grows 3.9 mm, 1.1 mm gap left (Python)');
  check((await t('.tx-state')).includes('It would close at 52.05 °C'), 'expansion: gap closes at 52.05 °C');
  check((await t('.tx-facts')).includes('4.68 mm') && (await t('.tx-facts')).includes('300 millionths'), 'expansion: gap for 50 °C 4.68 mm, strain 300 millionths');
  const inked = await page.$eval(R + '.tx-cv', (c) => { const d = c.getContext('2d').getImageData(0, 0, c.width, c.height).data; let n = 0; for (let i = 0; i < d.length; i += 4) if (d[i] < 150 || Math.abs(d[i] - d[i + 2]) > 60) n++; return n; });
  check(inked > 400, `expansion: picture drawn (${inked})`);
  check(await page.isHidden(R + '.tx-seq'), 'expansion: stress card hidden at Class 8–10');
  await slide('.tx-T', 60);
  check((await t('.tx-state')).includes('The gap closed at 52.05 °C') && (await t('.tx-facts')).includes('about 7.8 cm'), 'expansion: at 60 °C the gap has closed; bow about 7.8 cm (Python)');
  await slide('.tx-T', 45);
  await page.selectOption(R + '.tx-mat', 'aluminium'); await page.waitForTimeout(150);
  check((await t('.tx-eq')).includes('= 7.47 mm') && (await t('.tx-state')).includes('closed at 36.72 °C'), 'expansion: aluminium grows 7.47 mm and closes at 36.72 °C');
  await page.selectOption(R + '.tx-mat', 'steel');
  await slide('.tx-T', 0);
  check((await t('.tx-eq')).includes('= −3.12 mm') && (await t('.tx-eq')).includes('= 8.12 mm.'), 'expansion: cooling shrinks the rail and widens the gap');
  await slide('.tx-T', 45);
  await page.click(R + '[data-level="11"]'); await page.waitForTimeout(150);
  check((await t('.tx-seq')).includes('= 60 MPa (compression)') && (await t('.tx-seq')).includes('462 kN'), 'expansion: welded steel +25 °C: 60 MPa, 462 kN');
  check((await t('.tx-aeq')).includes('ΔA ≈ 2α A ΔT = 6 cm² (exact 6.001 cm²)') && (await t('.tx-aeq')).includes('900 cm³ (exact 900.3 cm³)'), 'expansion: area 2α and volume 3α');
  await page.click(R + '[data-m="bridge"]'); await page.waitForTimeout(150);
  check((await page.$eval(R + '.tx-mat', (e) => e.value)) === 'concrete' && (await t('.tx-eq')).includes('× 40 m ×') && (await t('.tx-eq')).includes('= 12 mm.') && !(await t('.tx-seq')).includes('kN'), 'expansion: bridge 40 m concrete grows 12 mm');
  await slide('.tx-g', 0);
  check((await t('.tx-state')).includes('closed'), 'expansion: no gap closes at once');
  await slide('.tx-L', 200);
  check((await t('.tx-Lv')) === '200 m', 'expansion: bridge length slider');
  await page.click(R + '[data-m="rail"]'); await page.waitForTimeout(100);
  check((await t('.tx-Lv')) === '13 m', 'expansion: back to rail');
  await slide('.tx-T0', -5);
  check((await t('.tx-T0v')) === '−5 °C', 'expansion: laying temperature slider');
  const items = await page.$$(R + '.lq-item');
  check(items.length === 5, 'expansion: five questions');
  const ans = await items[0].getAttribute('data-ans');
  await (await items[0].$('.lq-in')).fill(String(+(+ans).toPrecision(3))); await (await items[0].$('.lq-check')).click();
  check((await (await items[0].$('.lq-fb')).textContent()) === 'Right.', 'expansion: rail growth answer accepted');
  const ch = await items[4].$$('.lq-choice'), right = +(await items[4].getAttribute('data-ans'));
  await ch[right].click();
  check((await (await items[4].$('.lq-fb')).textContent()) === 'Right.', 'expansion: choice question');
};
