// #316 home range analyser. Reference values from an independent Python check (shapely 2.2 convex hulls on a
// pyproj azimuthal equidistant projection, pyproj.Geod geodesic polygon area, numpy kernel density on a 600 × 600
// grid, numpy step lengths and turning angles) on the page's made-up collar data; plus the analytic area of the
// isopleths of a single normal kernel: pi h^2 2 ln(1/(1 - p)).
import { project, hull, area, mcp, href, kde, isopleth, steps, resultant, readTime, quantile } from '../../src/lib/sci/homerange.ts';

export default async (check) => {
  const near = (name, a, b, rel) => check(`home range: ${name} (${a} vs ${b})`, Math.abs(a - b) <= rel * Math.abs(b));
  const rows = EXAMPLE.trim().split('\n').slice(1).map((l) => l.split('\t'));
  const { pts } = project(rows.map((r) => ({ lat: +r[1], lon: +r[2] })));
  const m100 = mcp(pts), m95 = mcp(pts, 95);
  near('100 % MCP area vs shapely on aeqd projection', m100.area, 2323684.83, 1e-4);
  near('100 % MCP area vs geodesic area', m100.area, 2323684.83, 1e-4);
  check('home range: 100 % MCP has 10 corners, as shapely', m100.poly.length === 10);
  near('95 % MCP area vs shapely', m95.area, 1817149.63, 1e-4);
  check('home range: 95 % MCP keeps 171 of 180 fixes', m95.used === 171);
  const h = href(pts);
  near('reference bandwidth', h, 194.45167, 1e-5);
  const k = kde(pts, h, 200);
  near('KDE 50 % area vs numpy', isopleth(k, 50).area, 866196.0, 2e-3);
  near('KDE 95 % area vs numpy', isopleth(k, 95).area, 3152023.1, 2e-3);
  const k3 = kde(pts, 300, 200);
  near('KDE 50 % with h = 300 m', isopleth(k3, 50).area, 1195186.7, 2e-3);
  near('KDE 95 % with h = 300 m', isopleth(k3, 95).area, 4380103.7, 2e-3);
  const one = kde([{ x: 0, y: 0 }], 100, 200);
  near('one kernel: 95 % area = 2 pi h^2 ln 20', isopleth(one, 95).area, 2 * Math.PI * 1e4 * Math.log(20), 2e-3);
  near('one kernel: 50 % area = 2 pi h^2 ln 2', isopleth(one, 50).area, 2 * Math.PI * 1e4 * Math.log(2), 2e-3);
  let tot = 0; for (const v of k.dens) tot += v; near('density integrates to 1', tot * k.cell * k.cell, 1, 1e-6);
  const st = steps(pts, rows.map((r) => readTime(r[0]))), L = st.map((s) => s.len), T = st.map((s) => s.turn).filter(Number.isFinite);
  near('mean step length vs numpy', L.reduce((a, b) => a + b) / L.length, 469.92179, 1e-4);
  near('longest step vs numpy', Math.max(...L), 1616.7897, 1e-4);
  near('mean absolute turning angle', T.reduce((a, b) => a + Math.abs(b), 0) / T.length, 94.744911, 1e-4);
  near('mean resultant length of turns', resultant(T).r, 0.0929062, 1e-3);
  check('home range: 4 h between fixes', st[0].dt === 14400 && Math.abs(st[0].speed - st[0].len / 14400) < 1e-12);
  // Small hand checks.
  near('unit square hull area', area(hull([{ x: 0, y: 0 }, { x: 1, y: 0 }, { x: 1, y: 1 }, { x: 0, y: 1 }, { x: 0.5, y: 0.5 }])), 1, 1e-12);
  const tr = steps([{ x: 0, y: 0 }, { x: 0, y: 10 }, { x: 10, y: 10 }, { x: 10, y: 0 }], [0, 1000, 2000, 3000]);
  check('home range: headings 0, 90, 180 and right turns of +90', tr[0].heading === 0 && tr[1].heading === 90 && tr[2].heading === 180 && tr[1].turn === 90 && tr[2].turn === 90 && Number.isNaN(tr[0].turn));
  near('type 7 quantile', quantile([1, 2, 3, 4], 0.95), 3.85, 1e-12);
  check('home range: time stamps', readTime('2026-05-01 06:00') === Date.UTC(2026, 4, 1, 6) && readTime('2026-05-01T06:00:30Z') === Date.UTC(2026, 4, 1, 6, 0, 30) && Number.isNaN(readTime('soon')));
};

